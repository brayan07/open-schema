# Level 2 has a mottled 2/1 strip down column 8; two boxes started on it,
# and removing one revealed the strip underneath.  The strip is patched into
# the static layer for rendering; PASSABLE says the player may walk on it.
STRIP = ('2122', '1222', '2221', '2212')
PATCH = {2: dict(((r, 8), STRIP) for r in range(N))}
# The strip blocks both carriers; boxes may be parked on it, which is how a
# box is handed from the left half of the board to the right half.
BOX_PARK = {2: set((r, 8) for r in range(N))}

# Container cells per level.  They must be hard-coded: the harness re-inits
# the model from the *current* frame, where a stored box hides its cell.
SLOTS = {
    0: [(7, 7), (7, 8), (7, 9)],
    1: [(7, 3), (7, 4), (8, 3), (8, 4), (9, 3), (9, 4)],
    2: [(6, 13), (6, 14), (7, 13), (7, 14), (8, 13), (8, 14),
        (9, 13), (9, 14)],
    3: [(5, 14), (6, 1), (7, 1), (7, 13), (9, 2), (14, 9), (14, 10)],
    4: [(6, 2), (6, 3), (7, 2), (7, 3), (8, 2), (8, 3), (9, 2), (9, 3)],
}

DELTA = {1: (-1, 0), 2: (1, 0), 3: (0, -1), 4: (0, 1)}


def _norm(grid):
    if grid and isinstance(grid[0], str):
        return list(grid)
    return [''.join('%x' % v for v in row) for row in grid]


def _denorm(rows):
    return [[int(ch, 16) for ch in row] for row in rows]


def _cell(grid, r, c):
    return tuple(grid[4 * r + i][4 * c:4 * c + 4] for i in range(4))


def _player_sprite(face):
    g = [[BODY] * 4 for _ in range(4)]
    if face == 1:
        for j in range(4):
            g[0][j] = HEAD
    elif face == 2:
        for j in range(4):
            g[3][j] = HEAD
    elif face == 3:
        for i in range(4):
            g[i][0] = HEAD
    else:
        for i in range(4):
            g[i][3] = HEAD
    return tuple(''.join(r) for r in g)


PLAYER_SPRITES = {f: _player_sprite(f) for f in (1, 2, 3, 4)}


def _box_sprite(b):
    return (b * 4, b + '99' + b, b + '99' + b, b * 4)


def _is_box(cl):
    for b in BOX_BORDERS:
        if cl == _box_sprite(b):
            return b
    return None


def _parse(grid):
    player = face = None
    blocks = []
    boxes = {}
    for r in range(N):
        for c in range(N):
            cl = _cell(grid, r, c)
            hit = False
            for f, sp in PLAYER_SPRITES.items():
                if cl == sp:
                    player, face, hit = (r, c), f, True
                    break
            if hit:
                continue
            if cl == BLOCK:
                blocks.append((r, c))
                continue
            b = _is_box(cl)
            if b is not None:
                boxes[(r, c)] = b
    return player, face, boxes, blocks


def _template(grid):
    rows = [list(row) for row in grid]
    player, _face, boxes, blocks = _parse(grid)
    movers = list(boxes) + list(blocks) + ([player] if player else [])
    for (r, c) in movers:
        for i in range(4):
            for j in range(4):
                rows[4 * r + i][4 * c + j] = BG
    rows[63] = list('7' * SIZE)
    return [''.join(row) for row in rows]


def _blocked_static(tmpl, r, c):
    if not (0 <= r < N and 0 <= c < N):
        return True
    return any(ch != BG for row in _cell(tmpl, r, c) for ch in row)


def _rival_free(tmpl, slots, boxes, cell):
    """The rival walks on floor and on container cells, never on boxes."""
    r, c = cell
    if not (0 <= r < N and 0 <= c < N) or cell in boxes:
        return False
    return (cell in slots) or not _blocked_static(tmpl, r, c)


def _reach(tmpl, slots, boxes, start):
    seen = {start}
    q = [start]
    while q:
        nxt = []
        for cell in q:
            for dr, dc in DELTA.values():
                n2 = (cell[0] + dr, cell[1] + dc)
                if n2 in seen:
                    continue
                if _rival_free(tmpl, slots, boxes, n2):
                    seen.add(n2)
                    nxt.append(n2)
        q = nxt
    return seen


def _box_ok(tmpl, slots, cell):
    """A carried box may sit on floor, in a container cell, or on a strip
    cell (that is how a box is handed across a strip wall)."""
    r, c = cell
    if not (0 <= r < N and 0 <= c < N):
        return False
    if cell in slots or _cell(tmpl, r, c) == STRIP:
        return True
    return not _blocked_static(tmpl, r, c)


def _slots(tmpl):
    """Container cells: static furniture whose fill colour is 2."""
    out = []
    for r in range(N - 1):
        for c in range(N):
            if '2' in ''.join(_cell(tmpl, r, c)):
                out.append((r, c))
    return out


def init_state(entry_grid):
    rows = _norm(entry_grid)
    tmpl = _template(rows)
    p = rows[63].count('4')
    n = N_OVERRIDE if (p and N_OVERRIDE is not None) else 0
    slots = SLOTS.get(CURRENT_LEVEL)
    if slots is None:
        slots = _slots(tmpl)
    ent = LEVEL_ENTRY.get(CURRENT_LEVEL)
    grid = [list(r) for r in tmpl]
    if ent is not None:
        for (r, c) in slots:
            for i in range(4):
                for j in range(4):
                    grid[4 * r + i][4 * c + j] = ent[4 * r + i][4 * c + j]
    for (r, c), pat in PATCH.get(CURRENT_LEVEL, {}).items():
        for i in range(4):
            for j in range(4):
                grid[4 * r + i][4 * c + j] = pat[i][j]
    grid[63] = list('7' * SIZE)
    tmpl = [''.join(r) for r in grid]
    return {'tmpl': tmpl, 'n': n, 'slots': list(slots)}


# The bar looks like a budget gauge: 64 px spread over the level's action
# allowance (level 0 ~192 actions, level 1 ~70).
BUDGET = {0: 200, 1: 70, 2: 100, 3: 100, 4: 128}


def _bar_px(n):
    return int(64.0 * n / BUDGET.get(CURRENT_LEVEL, 192) + 0.5)


def _render(tmpl, player, face, boxes, blocks, n):
    rows = [list(row) for row in tmpl]

    def blit(r, c, cl):
        for i in range(4):
            for j in range(4):
                rows[4 * r + i][4 * c + j] = cl[i][j]

    for (r, c), b in boxes.items():
        blit(r, c, _box_sprite(b))
    for blk in blocks:
        blit(blk[0], blk[1], BLOCK)
    if player:
        blit(player[0], player[1], PLAYER_SPRITES[face])
    for i in range(min(SIZE, _bar_px(n))):
        rows[63][SIZE - 1 - i] = '4'
    return [''.join(row) for row in rows]


def _dists(src, blocked):
    """BFS distances from src over cells not in `blocked`."""
    dist = {src: 0}
    q = [src]
    while q:
        nxt = []
        for cell in q:
            for dr, dc in DELTA.values():
                n2 = (cell[0] + dr, cell[1] + dc)
                if n2 in dist or not (0 <= n2[0] < N and 0 <= n2[1] < N):
                    continue
                dist[n2] = dist[cell] + 1
                if n2 not in blocked:
                    nxt.append(n2)
        q = nxt
    return dist


def _step_toward(src, dst, blocked):
    """First step of a shortest path src->dst avoiding `blocked`.

    Ties are broken toward the column difference first, which is what the
    rival was observed to do in open ground.
    """
    if src == dst:
        return (0, 0)
    dist = {dst: 0}
    q = [dst]
    while q:
        nxt = []
        for cell in q:
            for dr, dc in DELTA.values():
                n2 = (cell[0] + dr, cell[1] + dc)
                if n2 in dist or not (0 <= n2[0] < N and 0 <= n2[1] < N):
                    continue
                if n2 in blocked and n2 != src:
                    continue
                dist[n2] = dist[cell] + 1
                nxt.append(n2)
        q = nxt
    if src not in dist:
        return (0, 0)
    want = []
    if dst[1] != src[1]:
        want.append((0, 1 if dst[1] > src[1] else -1))
    if dst[0] != src[0]:
        want.append((1 if dst[0] > src[0] else -1, 0))
    for dr, dc in DELTA.values():
        if (dr, dc) not in want:
            want.append((dr, dc))
    for dr, dc in want:
        cell = (src[0] + dr, src[1] + dc)
        if dist.get(cell, 1e9) == dist[src] - 1:
            return (dr, dc)
    return (0, 0)


def _faced(player, face):
    dr, dc = DELTA[face]
    return (player[0] + dr, player[1] + dc)


def _rival(block, boxes, colour0, slots, grabbed, player, tmpl, faced,
           others=()):
    """The colour-c rival, a second carrier with the same abilities.

    held (border 5) -> carry one cell toward the nearest empty container
    cell, and once the box sits in one, spend a step releasing it.
    Otherwise walk to the nearest box that is not already stored and spend
    a step grabbing it.  Returns (block, boxes, rival_held_box).
    """
    held = [k for k in boxes if colour0.get(k) == '5' and k != grabbed
            and abs(k[0] - block[0]) + abs(k[1] - block[1]) == 1]
    if not held:
        # A box the player faces shows 3 even while the rival holds it, and
        # the rival freezes until the player looks away.
        claimed = [k for k in boxes
                   if k not in slots and k != grabbed
                   and colour0.get(k) == '3'
                   and abs(k[0] - block[0]) + abs(k[1] - block[1]) == 1]
        if claimed and claimed[0] != faced:
            held = claimed
    if held:
        box = held[0]
        if box in slots:
            return block, boxes, None            # release step
        empty = [t for t in slots if t not in boxes]
        if not empty:
            return block, boxes, box
        off = (block[0] - box[0], block[1] - box[1])
        solid = set(boxes) - {box} | {player} | set(others)
        walls = set((r, c) for r in range(N) for c in range(N)
                    if _blocked_static(tmpl, r, c) and (r, c) not in slots)
        blocked = set()
        for r in range(N):
            for c in range(N):
                cell = (r, c)
                mate = (r + off[0], c + off[1])
                if cell in solid or cell in walls and cell not in slots:
                    blocked.add(cell)
                elif not (0 <= mate[0] < N and 0 <= mate[1] < N):
                    blocked.add(cell)
                elif mate in solid or mate in walls:
                    blocked.add(cell)
        blocked.discard(box)
        dd = _dists(box, blocked)
        tgt = sorted(empty, key=lambda t: (dd.get(t, 999), t))[0]
        dr, dc = _step_toward(box, tgt, blocked)
        if (dr, dc) == (0, 0):
            return block, boxes, box
        nb = (block[0] + dr, block[1] + dc)
        nbox = (box[0] + dr, box[1] + dc)
        if not (0 <= nbox[0] < N and 0 <= nbox[1] < N):
            return block, boxes, box
        if nbox in boxes and nbox != box:
            return block, boxes, box
        out = {(nbox if k == box else k): v for k, v in boxes.items()}
        return nb, out, nbox
    cand = [k for k in boxes if k not in slots and k != grabbed]
    if cand:
        reach = _reach(tmpl, slots, set(boxes) | set(others), block)
        cand = [k for k in cand
                if any((k[0] + dr, k[1] + dc) in reach
                       for dr, dc in DELTA.values())]
    if not cand:
        return block, boxes, None
    # a box the player is right next to is left for the player
    far = [k for k in cand
           if abs(k[0] - player[0]) + abs(k[1] - player[1]) > 2]
    if far:
        cand = far
    adj = [k for k in cand
           if abs(k[0] - block[0]) + abs(k[1] - block[1]) == 1]
    if adj:
        if adj[0] == faced:
            return block, boxes, None            # frozen by the player
        return block, boxes, adj[0]              # grab step
    blocked = set(boxes) | {player} | set(others)
    blocked |= set((r, c) for r in range(N) for c in range(N)
                   if _blocked_static(tmpl, r, c) and (r, c) not in slots)
    dd = _dists(block, blocked)
    cand = sorted(cand, key=lambda k: (dd.get(k, 999), k))
    tgt = cand[0]
    dr, dc = _step_toward(block, tgt, blocked)
    nb = (block[0] + dr, block[1] + dc)
    if not (0 <= nb[0] < N and 0 <= nb[1] < N) or nb in boxes:
        return block, boxes, None
    return nb, boxes, None


def predict(state, grid, action, x=None, y=None):
    tmpl, n, slots = state['tmpl'], state['n'], state['slots']
    rows = _norm(grid)
    player, face, boxes, blocks = _parse(rows)
    colour0 = dict(boxes)
    face0 = face
    moved = False
    grabbed = [k for k, v in boxes.items() if v == '0']
    g = grabbed[0] if grabbed else None

    if action in DELTA:
        dr, dc = DELTA[action]
        np_ = (player[0] + dr, player[1] + dc)
        ng = (g[0] + dr, g[1] + dc) if g else None
        moving = {np_} | ({ng} if ng else set())
        ok = (not _blocked_static(tmpl, np_[0], np_[1])
              and np_ not in blocks)
        if ok and ng is not None and (not _box_ok(tmpl, slots, ng)
                                      or ng in blocks):
            ok = False
        if ok:
            for k in boxes:
                if k != g and k in moving:
                    ok = False
        if ok:
            moved = True
            player = np_
            if g is not None:
                boxes = {(ng if k == g else k): v for k, v in boxes.items()}
                g = ng
        if g is None:
            face = action
    elif action == 5:
        if g is not None:
            boxes[g] = '4'
            g = None
        else:
            dr, dc = DELTA[face]
            tgt = (player[0] + dr, player[1] + dc)
            if tgt in boxes:
                boxes[tgt] = '0'
                g = tgt

    if g is not None:
        d = (g[0] - player[0], g[1] - player[1])
        for a, dd in DELTA.items():
            if dd == d:
                face = a

    faced = _faced(player, face)
    rheld = set()
    newblocks = []
    for i, blk in enumerate(blocks):
        others = set(blocks[:i]) | set(blocks[i + 1:])
        nb, boxes, held = _rival(blk, boxes, colour0, slots, g, player,
                                 tmpl, faced, others)
        newblocks.append(nb)
        if held:
            rheld.add(held)
    blocks = newblocks

    for k in list(boxes):
        if k == g:
            boxes[k] = '0'
        elif k in rheld:
            boxes[k] = '5'
        elif k == faced:
            boxes[k] = '3'
        else:
            boxes[k] = '4'

    n += 1
    out = _render(tmpl, player, face, boxes, blocks, n)
    # the level ends once every box is stored in the container
    done = bool(boxes) and all(k in slots and v not in ('0', '5')
                               for k, v in boxes.items())
    if done:
        nxt = LEVEL_ENTRY.get(CURRENT_LEVEL + 1)
        if nxt is not None:
            out = nxt
    return _denorm(out), {'level_up': done}, {'tmpl': tmpl, 'n': n,
                                              'slots': slots}
