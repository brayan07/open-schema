"""World model for tr87 — a translation/transliteration puzzle.

Screen
  rows 0..33  (bg 2)  legend: pairs  <source box> --333-- <dest box>
                      arranged in row bands, two pairs per band.
  rows 34..62 (bg 3)  rows 40..46 top banner  = the word to translate
                                               (source font)
                      rows 51..57 bottom banner = the answer, editable
                                               (dest font)
                      colour-0 bracket (3 rows above / below the banner)
                      marks the selected slot.
  row  63             bar: 64 cells, colour 1 -> 4 from the right,
                      one cell per 2 actions taken.

A box of border colour C and width 7*n holds n glyphs, each 5x5, at
cols c0+1+7*i, rows r0+1..r0+5, foreground colour 5.

Every glyph is drawn at some rotation; letter identity is the rotation
class.  Within the editable banner each slot has its OWN fixed rotation,
which never changes as the symbol is cycled.

Actions
  1 : next symbol of the dest alphabet's cyclic order at the selected slot
  2 : previous symbol
  3 : move selection left (wrap), 4 : move selection right (wrap)

The legend maps ONE source letter to a STRING of dest letters; the answer
is the concatenation of those strings for the top banner's letters.
"""

FG = 5
BRACKET = 0
TOP_R0, BOT_R0 = 40, 51


def rot(t, k=1):
    for _ in range(k % 4):
        t = tuple(''.join(t[4 - c][r] for c in range(5)) for r in range(5))
    return t


def canon(t):
    return min(rot(t, k) for k in range(4))


def boxes(grid, r_lo, r_hi):
    """all glyph boxes (border colour != background) inside [r_lo, r_hi]"""
    bg = grid[r_lo][0]
    seen = [[False] * 64 for _ in range(64)]
    out = []
    for r in range(r_lo, r_hi + 1):
        for c in range(64):
            v = grid[r][c]
            if v in (bg, FG) or seen[r][c]:
                continue
            st, cells, col = [(r, c)], [], v
            seen[r][c] = True
            while st:
                y, x = st.pop()
                cells.append((y, x))
                for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    ny, nx = y + dy, x + dx
                    if (r_lo <= ny <= r_hi and 0 <= nx < 64
                            and not seen[ny][nx]
                            and grid[ny][nx] in (col, FG)):
                        seen[ny][nx] = True
                        st.append((ny, nx))
            rs = [y for y, _ in cells]
            cs = [x for _, x in cells]
            r0, r1, c0, c1 = min(rs), max(rs), min(cs), max(cs)
            if r1 - r0 == 6 and (c1 - c0 + 1) % 7 == 0:
                out.append((r0, r1, c0, c1, col))
    return sorted(out)


def read_box(grid, box):
    r0, _, c0, c1, _ = box
    n = (c1 - c0 + 1) // 7
    return [tuple(''.join('#' if grid[r][x] == FG else '.'
                          for x in range(c0 + 1 + 7 * i, c0 + 6 + 7 * i))
                  for r in range(r0 + 1, r0 + 6))
            for i in range(n)]


def field_split(grid):
    """first row of the lower field (the two backgrounds differ)"""
    top_bg = grid[0][0]
    for r in range(64):
        if grid[r][0] != top_bg:
            return r
    return 34


def banners(grid):
    """(source word box, target word box) from the lower field"""
    bs = sorted(boxes(grid, field_split(grid), 62))
    return bs[0], bs[1]


def banner(grid, which):
    """which=TOP_R0 -> the given word, BOT_R0 -> the word to match"""
    return banners(grid)[0 if which == TOP_R0 else 1]


def cells(grid):
    """the ring of glyph cells the bracket can select, in cursor order.

    The bracket lives either in the lower field (then only the answer
    banner's slots are editable) or in the upper field (then every legend
    glyph is, in reading order)."""
    split = field_split(grid)
    up = any(grid[r][c] == BRACKET for r in range(split) for c in range(64))
    if up:
        # A legend box is ONE editable unit: the bracket spans the whole box
        # and cycling advances every glyph in it by one step together, so the
        # cyclic offset between a box's glyphs never changes.
        return [(b, tuple(range(len(slot_cols(b)))))
                for b in boxes(grid, 0, split - 1)]
    b = banner(grid, BOT_R0)
    return [(b, (i,)) for i in range(len(slot_cols(b)))]


def slot_cols(box):
    r0, _, c0, c1, _ = box
    return [c0 + 1 + 7 * i for i in range((c1 - c0 + 1) // 7)]


def read_cursor(grid):
    for j, (b, idx) in enumerate(cells(grid)):
        if grid[b[0] - 3][slot_cols(b)[idx[0]]] == BRACKET:
            return j
    return 0


def legend(grid):
    """[(from colour, to colour, source glyphs, dest glyphs)] from the legend"""
    bands = {}
    for b in boxes(grid, 0, field_split(grid) - 1):
        bands.setdefault(b[0], []).append(b)
    out = []
    for r0 in sorted(bands):
        row = sorted(bands[r0], key=lambda b: b[2])
        for i in range(0, len(row) - 1, 2):
            a, b = row[i], row[i + 1]
            out.append((a[4], b[4],
                        [canon(x) for x in read_box(grid, a)],
                        [canon(x) for x in read_box(grid, b)]))
    return out


def _apply(rules, word):
    """rewrite `word` with the given src->dst rules (longest match first)"""
    best = {len(word): []}

    def go(i):
        if i in best:
            return best[i]
        best[i] = None
        for src, dst in sorted(rules, key=lambda e: -len(e[0])):
            if word[i:i + len(src)] == src:
                rest = go(i + len(src))
                if rest is not None:
                    best[i] = dst + rest
                    break
        return best[i]

    return go(0)


def target(grid):
    """what the editable banner must show: the top word pushed through the
    legend, which may be a CHAIN of scripts (e.g. 10 -> 7 -> 11)."""
    leg = legend(grid)
    steps = {}
    for cf, ct, src, dst in leg:
        steps.setdefault((cf, ct), []).append((src, dst))
    a = banner(grid, TOP_R0)[4]
    b = banner(grid, BOT_R0)[4]
    # shortest chain of scripts from a to b
    q, seen = [(a, [])], {a}
    path = None
    while q:
        c, sofar = q.pop(0)
        if c == b:
            path = sofar
            break
        for (cf, ct) in steps:
            if cf == c and ct not in seen:
                seen.add(ct)
                q.append((ct, sofar + [(cf, ct)]))
    if path is None:
        return None
    word = [canon(x) for x in read_box(grid, banner(grid, TOP_R0))]
    for key in path:
        word = _apply(steps[key], word)
        if word is None:
            return None
    return word


def answer(grid):
    return [canon(g) for g in read_box(grid, banner(grid, BOT_R0))]


