def _sig(grid):
    """a level fingerprint that no action can change: the given word"""
    b = banners(grid)[0]
    return (b, tuple(read_box(grid, b)))


def cur_level(grid):
    sig = _sig(grid)
    for k, rows in ENTRY.items():
        g = [[int(ch, 16) for ch in r] for r in rows]
        if _sig(g) == sig:
            return int(k)
    return None


def p_off(cyc, vals, idx, p):
    """offset (in cycle steps) of glyph p of a box from its first glyph"""
    a = b = None
    for j, base in enumerate(cyc):
        for k in range(4):
            if rot(base, k) == vals[idx[0]]:
                a = j
            if rot(base, k) == vals[idx[p]]:
                b = j
    return 0 if a is None or b is None else (b - a) % len(cyc)


def slot_rot(key, slot, sym):
    """(cycle index, quarter-turns) of the glyph displayed in a cell"""
    for j, base in enumerate(CYCLES.get(key, [])):
        for k in range(4):
            if rot(base, k) == sym:
                return j, KFIX.get((key, slot), k)
    return None, 0


PARITY = 1   # parity of the true action count when a commit starts


def draw_glyph(grid, box, i, g):
    c0 = slot_cols(box)[i]
    for r in range(5):
        for c in range(5):
            grid[box[0] + 1 + r][c0 + c] = FG if g[r][c] == '#' else box[4]


def draw_bracket(grid, box, idx, on):
    top, bot = box[0] - 3, box[1] + 3
    v = BRACKET if on else grid[top][0]
    cs = slot_cols(box)
    c0, c1 = cs[idx[0]], cs[idx[-1]] + 4
    for c in range(c0, c1 + 1):
        grid[top][c] = v
        grid[bot][c] = v
    for r in (top + 1, bot - 1):
        grid[r][c0] = v
        grid[r][c1] = v


def init_state(entry_grid):
    used = sum(1 for v in entry_grid[63] if v == 4)
    return {'n': 2 * used + (PARITY if used else 0)}


def predict(state, grid, action, x=None, y=None):
    g = [list(row) for row in grid]
    ring = cells(g)
    cur = read_cursor(g)
    if action in (3, 4):
        n = len(ring)
        draw_bracket(g, ring[cur][0], ring[cur][1], False)
        cur = (cur - 1) % n if action == 3 else (cur + 1) % n
        draw_bracket(g, ring[cur][0], ring[cur][1], True)
    elif action in (1, 2):
        box, idx = ring[cur]
        lvl = cur_level(g)
        cyc = CYCLES.get((lvl, box[4]), [])
        vals = read_box(g, box)
        j, _ = slot_rot((lvl, box[4]), (cur, 0), vals[idx[0]])
        if j is not None and cyc:
            j = (j + 1) % len(cyc) if action == 1 else (j - 1) % len(cyc)
            for p, i in enumerate(idx):
                key = ((lvl, box[4]), (cur, p))
                jp = (j + p_off(cyc, vals, idx, p)) % len(cyc)
                t = SEEN.get(key, {}).get(canon(cyc[jp]))
                if t is None:
                    t = rot(cyc[jp], KFIX.get(key, 0))
                draw_glyph(g, box, i, t)

    n = state['n'] + 1
    r = RATE.get(str(cur_level(g)), 2)
    for k in range(64):
        g[63][k] = 4 if k >= 64 - n // r else 1

    tgt = target(g)
    up = tgt is not None and answer(g) == tgt
    if up:
        n = 0                      # the bar restarts with every level
        lvl = cur_level(grid)
        nxt = ENTRY.get(str(lvl + 1)) if lvl is not None else None
        if nxt:
            g = [[int(ch, 16) for ch in r] for r in nxt]
    return g, {'level_up': up}, {'n': n}

