"""World model for sk48.

Layout (derived from the frame, geometry changes per level):
  - The play FIELD is a solid rectangle of colour 4 (rows R0..R1, cols C0..C1).
  - The PLAYER is a 6x6 box (colour 6) just left of the field, cols C0-6..C0-1,
    rows T..T+5 with T = R0 + 6*i (bottom-most T = R1-5).
  - A striped POLE (2/3, period 6) fills cols C0-4..C0-3 over rows R0+2..R1-2
    (the player's track); it is hidden under the player.
  - The ARM is a 2-row beam at rows T+2,T+3 running from the player's right
    edge col C0-1 rightwards for L columns (L a multiple of 6, 6 <= L <= width).
    Texture: row T+2 -> 2 where (c-C0)%3==0 else 1 (edge cell C0-1 = 1);
             row T+3 -> 2 where (c-C0)%3==2 else 1 (edge cell C0-1 = 2).
  - BLOCKS are 4x4 coloured squares in the field.  Extending the arm passes
    through them; a block whose 4 columns lie inside the arm span and whose
    rows straddle the arm rows is *impaled* and then moves with the arm
    (retract: 6 left) and with the player (up/down).

Actions: 1 = up 6, 2 = down 6, 4 = extend +6, 3 = retract -6, 7 = undo,
         6 = click (no effect seen).

Bottom panel (rows 54+): the goal — the same player+arm with the blocks
threaded on it in the required order/offsets.  An icon is hollowed (inner 2x2
-> 0) once that block is held in the required order; all hollow => level up.

Row 53 is a clock: one cell (2 -> 3) filled from the right every 3 non-undo
actions; it resets at the start of each level.
"""

ARM = (1, 2)
BG, FIELD_BG = 5, 4


# ---------------------------------------------------------------- geometry

def geom(grid):
    """(R0, R1, C0, C1) of the play field."""
    rows = [r for r in range(53) if any(grid[r][c] == FIELD_BG
                                        for c in range(64))]
    R0, R1 = min(rows), max(rows)
    cols = [c for c in range(64) if grid[R0][c] == FIELD_BG]
    return R0, R1, min(cols), max(cols)


def _find_player(grid, R0, R1, C0):
    pc = C0 - 6
    for r in range(R0, R1 + 1):
        if grid[r][pc] == 6 and grid[r][pc + 1] == 6:
            return r
    return None


def _arm_len(grid, T, C0, C1):
    """Length of the contiguous arm run, tolerating blocks threaded on it and
    ignoring look-alike cells (the rope) beyond its tip."""
    row = grid[T + 2]
    last = C0 - 1
    for c in range(C0, C1 + 1):
        want = 2 if (c - C0) % 3 == 0 else 1
        if row[c] == want:
            last = c
        elif row[c] not in (FIELD_BG, BG) and row[c] not in ARM:
            continue            # a block threaded on the arm hides it
        else:
            break
    return last - (C0 - 1)


def _blocks(grid, R0, R1, C0, C1):
    out = []
    for r in range(R0, R1 + 1):
        for c in range(C0, C1 + 1):
            v = grid[r][c]
            if v in (FIELD_BG, BG) or v in ARM:
                continue
            up = grid[r - 1][c] if r > R0 else FIELD_BG
            left = grid[r][c - 1] if c > C0 else FIELD_BG
            if up != v and left != v:
                if (r + 3 <= R1 and c + 3 <= C1
                        and all(grid[r + i][c + j] == v
                                for i in range(4) for j in range(4))):
                    out.append((v, r, c))
    return out


ROPE_BOTTOM = 23        # last field row the cables reach (per level)


def ropes(grid):
    """[(left col, phase-anchor row, bottom row, anchor colour)] for every
    vertical cable in the field."""
    R0, R1, C0, C1 = geom(grid)
    cols = sorted({c for r in range(R0, R1 + 1) for c in range(C0, C1 + 1)
                   if grid[r][c] == 3})
    out = []
    for c in cols:
        if out and c - out[-1][0] == 1:
            continue                      # right half of the previous cable
        rs = [r for r in range(R0, R1 + 1) if grid[r][c] == 3]
        anchor = None
        for r in range(0, R0):
            for cc in (c, c + 1):
                v = grid[r][cc]
                if v not in (BG, FIELD_BG, 1, 2, 3):
                    anchor = v
        out.append((c, min(rs), max(rs), anchor))
    return out


def rope(grid):
    rs = ropes(grid)
    return (rs[0][0], rs[0][1], rs[0][2]) if rs else None


def parse(grid):
    R0, R1, C0, C1 = geom(grid)
    T = _find_player(grid, R0, R1, C0)
    return T, _arm_len(grid, T, C0, C1), _blocks(grid, R0, R1, C0, C1)


def _anchored(b, rps, R0):
    """A block hanging on a cable cannot move horizontally (it can still slide
    up and down along it)."""
    return _anchor_of(b, rps, R0) is not None


def _anchor_of(b, rps, R0):
    if not rps:
        return None
    _, r0, c0 = b
    for rc, _, rr1, colour in (rps or ()):
        if c0 <= rc + 1 and c0 + 3 >= rc and r0 <= rr1 and r0 + 3 >= R0:
            return colour
    return None


def _in_span(b, T, L, C0):
    _, r0, c0 = b
    return r0 <= T + 2 and r0 + 3 >= T + 3 and c0 >= C0 and c0 + 3 <= C0 - 1 + L


def _impaled(b, T, L, C0, spent=()):
    return _in_span(b, T, L, C0)


# ---------------------------------------------------------------- panel

def _panel_boxes(grid):
    """[(row0, right col, icon colour or None)] for each 6x6 box in the panel,
    left to right.  A box with an icon is a cable anchor; without, the arm."""
    out = []
    for r in range(54, 58):
        for c in range(64 - 6):
            b = grid[r][c]
            if b not in (5, 6):
                continue
            if not all(grid[r][c + j] == b and grid[r + 5][c + j] == b
                       for j in range(6)):
                continue
            if not all(grid[r + i][c] == b for i in range(6)):
                continue
            if not all(grid[r + i][c + 5] == b for i in (0, 1, 4, 5)):
                continue
            icon = grid[r + 2][c + 2]
            out.append((r, c + 5, None if icon in (0, b) else icon))
    return sorted(out, key=lambda t: t[1])


def _panel_anchor(grid):
    for r, pc, icon in _panel_boxes(grid):
        if icon is None:
            return r, pc
    return None, None


def panel_groups(grid):
    """[(icon, [(colour, offset), ...])] — one entry per box."""
    groups = []
    for r, pc, icon in _panel_boxes(grid):
        row = grid[r + 2]
        out = []
        c = pc + 1
        while c < 64:
            v = row[c]
            if v in (1, 2, 3):
                c += 1
            elif v in (FIELD_BG, BG):
                break
            else:
                out.append((v, c - pc))
                c += 4
        groups.append((icon, out))
    return groups


def goal_offsets(grid):
    for icon, blocks in panel_groups(grid):
        if icon is None:
            return blocks
    return []


def _held_prefix(blocks, T, L, C0):
    """How many leading goal blocks are correctly held: impaled, and lying in
    the goal order (increasing distance from the player)."""
    return blocks, T, L, C0


# ---------------------------------------------------------------- rendering

def render(grid, T, L, blocks, spent=()):
    R0, R1, C0, C1 = geom(grid)
    PC0 = C0 - 6
    g = [list(row) for row in grid]
    for r in range(R0, R1 + 1):
        for c in range(PC0, C1 + 1):
            if c >= C0:
                g[r][c] = FIELD_BG
            elif PC0 + 2 <= c <= PC0 + 3 and R0 + 2 <= r <= R1 - 2:
                g[r][c] = 2 if (r - (R0 + 2)) % 6 < 2 else 3
            else:
                g[r][c] = BG
    for r, c in holes(grid):
        g[r][c] = BG
    for rc, rr0, rr1, _ in ropes(grid):
        for r in range(R0, rr1 + 1):
            ph = (r - rr0) % 3
            g[r][rc] = 3 if ph == 0 else 2
            g[r][rc + 1] = 3 if ph == 1 else 2
    pat = [[6, 6, 6, 6, 6, 6],
           [6, 0, 0, 0, 0, 6],
           [6, 0, 6, 6, 0, 6],
           [6, 0, 6, 6, 0, 6],
           [6, 0, 0, 0, 0, 6],
           [6, 6, 6, 6, 6, 6]]
    for i in range(6):
        for j in range(6):
            g[T + i][PC0 + j] = pat[i][j]
    g[T + 2][C0 - 1] = 1
    g[T + 3][C0 - 1] = 2
    for c in range(C0, C0 - 1 + L + 1):
        g[T + 2][c] = 2 if (c - C0) % 3 == 0 else 1
        g[T + 3][c] = 2 if (c - C0) % 3 == 2 else 1
    for col, r0, c0 in blocks:
        for i in range(4):
            for j in range(4):
                g[r0 + i][c0 + j] = col
    # goal panel check-offs
    for r, pc, seq, ok in _group_state(g, T, L, blocks, spent):
        for i, (col, off) in enumerate(seq):
            v = 0 if ok[i] else col
            for a in (2, 3):
                for b in (1, 2):
                    g[r + a][pc + off + b] = v
    return [tuple(row) for row in g]


def _group_state(grid, T, L, blocks, spent=()):
    """[(box row, box right col, wanted sequence, how many are ticked)].

    A box without an icon is the player's arm: its sequence must be matched by
    the blocks threaded on the arm, ordered by distance.  A box with an icon is
    a cable: matched by the blocks hanging on that cable, top to bottom.
    Only a prefix that matches exactly is ticked."""
    R0, R1, C0, C1 = geom(grid)
    rps = ropes(grid)
    out = []
    for (r, pc, icon), (_, seq) in zip(_panel_boxes(grid), panel_groups(grid)):
        if icon is None:
            held = sorted((b for b in blocks if _impaled(b, T, L, C0, spent)),
                          key=lambda b: b[2])
        else:
            held = sorted((b for b in blocks
                           if _anchor_of(b, rps, R0) == icon),
                          key=lambda b: b[1])
        cols = [b[0] for b in held]
        ok = [i < len(cols) and cols[i] == col
              for i, (col, _) in enumerate(seq)]
        out.append((r, pc, seq, ok))
    return out


def _at_goal(grid, T, L, blocks, spent=()):
    st = _group_state(grid, T, L, blocks, spent)
    return bool(st) and all(all(ok) and ok for _, _, _, ok in st)


def holes(grid):
    """Cells inside the field that are not field: static obstacles."""
    R0, R1, C0, C1 = geom(grid)
    return {(r, c) for r in range(R0, R1 + 1) for c in range(C0, C1 + 1)
            if grid[r][c] == BG}


def _set_clock(g, count):
    g = [list(row) for row in g]
    for c in range(64):
        g[53][c] = 3 if c >= 64 - count else 2
    return [tuple(row) for row in g]


# ---------------------------------------------------------------- dynamics

def _collide(a, b):
    cells = set()
    for _, r0, c0 in a:
        for i in range(4):
            for j in range(4):
                cells.add((r0 + i, c0 + j))
    for _, r0, c0 in b:
        for i in range(4):
            for j in range(4):
                if (r0 + i, c0 + j) in cells:
                    return True
    return False


def _move(grid, action, spent=()):
    """(T, L, blocks) after the action, or None if it is blocked."""
    R0, R1, C0, C1 = geom(grid)
    T, L, blocks = parse(grid)
    hol = holes(grid)

    def free_cell(r0, c0):
        return not any((r0 + i, c0 + j) in hol
                       for i in range(4) for j in range(4))

    def arm_ok(t, ln):
        return not any((t + 2 + i, c) in hol
                       for i in (0, 1) for c in range(C0, C0 + ln))
    imp = [b for b in blocks if _impaled(b, T, L, C0, spent)]
    oth = [b for b in blocks if not _impaled(b, T, L, C0, spent)]

    if action in (1, 2):
        d = -6 if action == 1 else 6
        nT = T + d
        if nT < R0 or nT + 5 > R1:
            return None
        if not arm_ok(nT, L):
            return None
        inspan = [b for b in blocks
                  if b[2] >= C0 and b[2] + 3 <= C0 - 1 + L]
        # blocks the bar carries (threaded) and blocks it sweeps into both
        # travel; a travelling block shoves whatever is in its way
        move = {id(b): b for b in inspan
                if (b[1] <= T + 2 and b[1] + 3 >= T + 3)
                or (b[1] <= nT + 2 and b[1] + 3 >= nT + 3)}
        changed = True
        while changed:
            changed = False
            for b in list(move.values()):
                nr = b[1] + d
                if nr < R0 or nr + 3 > R1 or not free_cell(nr, b[2]):
                    return None
                for o in blocks:
                    if id(o) in move or o[2] != b[2]:
                        continue
                    if nr <= o[1] + 3 and nr + 3 >= o[1]:
                        move[id(o)] = o
                        changed = True
        out = []
        for b in blocks:
            out.append((b[0], b[1] + d, b[2]) if id(b) in move else b)
        cells = set()
        for _, r0, c0 in out:
            for i in range(4):
                for j in range(4):
                    if (r0 + i, c0 + j) in cells:
                        return None
                    cells.add((r0 + i, c0 + j))
        return nT, L, out

    if action == 4:
        nL = L + 6
        if C0 - 1 + nL > C1 or not arm_ok(T, nL):
            return None
        # the arm carries what it has threaded outward with the tip, shoving
        # whatever those blocks run into (chain), until something jams
        row = sorted([b for b in blocks
                      if b[1] <= T + 2 and b[1] + 3 >= T + 3],
                     key=lambda b: b[2])
        rest = [b for b in blocks if b not in row]
        n = len(row)
        rp = ropes(grid)
        can = [False] * n
        for i in range(n - 1, -1, -1):
            free = (row[i][2] + 6 + 3 <= C1
                    and free_cell(row[i][1], row[i][2] + 6)
                    and not _anchored(row[i], rp, R0)
                    and not _anchored((row[i][0], row[i][1], row[i][2] + 6),
                                      rp, R0))
            if i < n - 1 and row[i + 1][2] - row[i][2] <= 6:
                free = free and can[i + 1]
            can[i] = free
        mv = [False] * n
        for i in range(n):
            want = (row[i][2] >= C0 and row[i][2] + 3 <= C0 - 1 + nL)
            if not want and i > 0 and mv[i - 1] and row[i][2] - row[i - 1][2] <= 6:
                want = True
            mv[i] = want and can[i]
        out = [(c, r, c0 + (6 if mv[i] else 0))
               for i, (c, r, c0) in enumerate(row)]
        return T, nL, out + rest

    if action == 3:
        nL = L - 6
        if nL < 0:
            return None
        # every impaled block is dragged 6 left unless something is in the
        # way (field edge, or a block that is itself stuck).  The arm always
        # shortens, so a block left behind past the new tip falls off it.
        taken = set()
        for _, r0, c0 in oth:
            for i in range(4):
                for j in range(4):
                    taken.add((r0 + i, c0 + j))
        out = []
        rp = ropes(grid)
        for col, r0, c0 in sorted(imp, key=lambda b: b[2]):
            nc = c0 - 6 if not _anchored((col, r0, c0), rp, R0) else c0
            cells = {(r0 + i, nc + j) for i in range(4) for j in range(4)}
            if (nc >= C0 and not (cells & taken)
                    and free_cell(r0, nc)
                    and not _anchored((col, r0, nc), rp, R0)):
                c0 = nc
            else:
                cells = {(r0 + i, c0 + j) for i in range(4) for j in range(4)}
            taken |= cells
            out.append((col, r0, c0))
        return T, nL, out + oth
    return T, L, blocks


# ---------------------------------------------------------------- api

# Non-undo actions taken *in the current level* when a mid-run state is handed
# to init_state (commit / bfs).  The run's very first frame is recognised and
# gets 0 so that backtest replays correctly.
K_START = 47

# One action in the current level was not counted by the game's clock (the
# tick pattern slipped by one after this many model-counted actions).
FREE_ACTIONS = {1: (51,)}
LEVEL_OFF = {4: 2}       # levels where the clock counts the level-up      # per level: actions the game's clock skipped
LEVEL_START = 2                # level index for a mid-run init_state

# Colours of blocks that have already been threaded once and released: the arm
# can no longer impale them, it only shoves them along.  (Not visible in a
# single frame, so it has to be carried in for mid-run inits.)
SPENT_START = ()


def _level_of(g):
    """Which level a state belongs to (needed only for the clock fudge)."""
    if geom(g) == (12, 41, 17, 46):
        return 0
    if holes(g):
        return 4
    rs = ropes(g)
    if len(rs) > 1:
        return 3
    if rs:
        return 2
    return 1


def _is_run_start(g):
    """A pristine level entry: clock empty, player parked at the bottom of the
    pole, arm at minimum extension."""
    R0, R1, C0, C1 = geom(g)
    T = _find_player(g, R0, R1, C0)
    return list(g[53]).count(3) == 0 and T == R1 - 5


def init_state(entry_grid):
    g = [list(r) for r in entry_grid]
    fresh = _is_run_start(g)
    return {"n": 0, "k": 0 if fresh else K_START, "stack": (),
            "spent": () if fresh else tuple(SPENT_START),
            "lvl": _level_of(g)}


def predict(state, grid, action, x=None, y=None):
    grid = tuple(tuple(r) for r in grid)
    n = state["n"]
    k = state.get("k", 0)
    stack = state["stack"]
    info = {}

    spent = tuple(state.get("spent", ()))
    if action == 7:
        ng, sp = stack[-1] if stack else (grid, spent)
        nstack = stack[:-1] if stack else ()
        spent = sp
    else:
        res = _move(grid, action, spent)
        noop = res is None or action == 6
        if noop:
            ng = grid
            k -= 1          # a no-op / blocked action does not tick the clock
        else:
            T0, L0, b0 = parse(grid)
            held0 = {b[0] for b in b0 if _impaled(b, T0, L0, geom(grid)[2],
                                                 spent)}
            T, L, blocks = res
            held1 = {b[0] for b in blocks
                     if _impaled(b, T, L, geom(grid)[2], spent)}
            # a block that slipped off the arm is spent — but one still hanging
            # on the cable was never really released
            # (blocks are never "used up": whether the tip threads or shoves
            # one depends only on whether it can be shoved)
            ng = render(grid, T, L, blocks, spent)
            if _at_goal(ng, T, L, blocks, spent):
                info["level_up"] = True
        nstack = stack if noop else stack + ((grid,
                                             tuple(state.get("spent", ()))),)
        k += 1

    if info.get("level_up"):
        spent = ()
        nxt = LEVEL_ENTRY.get(_sig(grid))
        if nxt is not None:
            ng = [tuple(int(ch, 16) for ch in row) for row in nxt]
        k = 0
    else:
        lv = state.get("lvl", 0)
        eff = k + LEVEL_OFF.get(lv, 0)
        ng = _set_clock(ng, max(0, (eff - 1) // 3))
    lvl = state.get("lvl", 0) + (1 if info.get("level_up") else 0)
    return ng, info, {"n": n + 1, "k": k, "stack": nstack, "spent": spent,
                      "lvl": lvl}


def _sig(grid):
    T, L, b = parse(grid)
    return (geom(grid), tuple(sorted(b)))


