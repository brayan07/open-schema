def _layout_ok(st, groups):
    """Every group's anchor blob must land on open ground."""
    base, marks = st["base"], st["markset"]
    for gp in groups:
        anc = _centroid(gp["pts"])
        for px, py in _blob_cells(*anc):
            if not _open(base, marks, px, py):
                return False
    return True


_RING_SET = frozenset((dx, dy) for dy in range(-4, 5) for dx in range(-4, 5)
                     if abs(dx) + abs(dy) == 4 and dx and dy)


def _ring_offsets():
    return [(dx, dy) for dy in range(-4, 5) for dx in range(-4, 5)
            if abs(dx) + abs(dy) == 4 and dx and dy]


def _angle(dx, dy):
    return math.degrees(math.atan2(dx, -dy)) % 360.0


def _pie_colour(pie, dx, dy):
    """Colour a group paints at offset (dx,dy) of any of its round sprites.

    The anchor blob and the target ring both sample one fixed angular colour
    partition per group (a single colour in levels 0-2, up to three in 3),
    so the blob's 20 samples decide every ring cell by nearest angle.
    """
    if (dx, dy) in pie:
        return pie[(dx, dy)]
    a = _angle(dx, dy)
    best, bestd = None, 1e9
    for (ox, oy), v in pie.items():
        d = abs(_angle(ox, oy) - a)
        d = min(d, 360.0 - d)
        if d < bestd:
            best, bestd = v, d
    return best


def _find_rings(base):
    """Ring markers left in the terrain: 12 diagonal cells at L1==4, with the
    4 axis cells of that ring and the centre still floor (kills terrain blobs)."""
    offs = _ring_offsets()
    out = []
    for y in range(4, 60):
        for x in range(4, 60):
            if base[y][x] not in (FLOOR, LINE):
                continue
            if any(base[y + d][x] not in (FLOOR, LINE)
                   or base[y][x + d] not in (FLOOR, LINE) for d in (-4, 4)):
                continue
            vals = [base[y + dy][x + dx] for dx, dy in offs]
            if all(v != FLOOR for v in vals) and \
                    sum(1 for v in vals if v not in (LINE,) + _BLOCKED) >= 6:
                # A ring cell painted in a terrain colour belongs to the map,
                # not to the sprite: it stays under the segments.
                out.append(((x, y), {(dx, dy): v
                                     for (dx, dy), v in zip(offs, vals)
                                     if v not in (LINE,) + _BLOCKED}))
    return out


_ENTRY_BLOBS = {}
_ENTRY_RINGS = {}


def _entry_rings(level):
    """Rings are static, so read them from the level's entry frame: in a later
    frame a segment can sit on a ring cell and hide it."""
    if level not in _ENTRY_RINGS:
        entry = _entry_for(level)
        if entry is None:
            _ENTRY_RINGS[level] = None
        else:
            cov = set()
            for pos, _ in _find_blobs(entry):
                cov |= set(_blob_cells(*pos))
            for pos, _, _ in _scan(entry, cov):
                cov |= set(_diamond(*pos))
            b = _copy(entry)
            for y in range(64):
                for x in range(1, 64):
                    if (x, y) in cov:
                        b[y][x] = FLOOR
            _ENTRY_RINGS[level] = _find_rings(b)
    return _ENTRY_RINGS[level]


def _entry_blobs(level):
    if level not in _ENTRY_BLOBS:
        entry = _entry_for(level)
        _ENTRY_BLOBS[level] = dict(_find_blobs(entry)) if entry else {}
    return _ENTRY_BLOBS[level]


def init_state(entry_grid):
    g = entry_grid
    blobs = _find_blobs(g)
    covered = set()
    for pos, _ in blobs:
        covered |= set(_blob_cells(*pos))
    ends = _scan(g, covered)
    # A node can hide inside a pick-up blob (its ring 0/3 blends with the
    # blob's empty cells); its centre colour still gives it away.
    cols = {c for _, _, c in ends}
    extra = [((x, y), g[y][x + 1], g[y][x]) for (x, y) in sorted(covered)
             if g[y][x] in cols and (x, y) not in {p for p, _, _ in ends}
             and all(g[y + dy][x + dx] in (RING_SEL, RING_UNSEL)
                     for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)))]
    parts = None
    for r in range(len(extra) + 1):
        for combo in itertools.combinations(range(len(extra)), r):
            cand = ends + [extra[i] for i in combo]
            parts = _split_groups(cand, {p for p, _ in blobs})
            if parts:
                ends = cand
                break
        if parts:
            break
    parts = parts or []
    # Nodes are painted over pick-up blobs, so drop node cells before reading
    # a blob's pie; _pie_colour interpolates the missing samples by angle.
    nodecells = set()
    for pos, _, _ in ends:
        nodecells |= set(_diamond(*pos))
    bpie = {pos: {k: v for k, v in pie.items()
                  if (pos[0] + k[0], pos[1] + k[1]) not in nodecells}
            for pos, pie in blobs}
    blobs = [(pos, bpie[pos]) for pos, _ in blobs]
    groups = []
    sel = None
    for gi, blk in enumerate(parts):
        pts = [ends[i][0] for i in blk]
        anc = _centroid(pts)
        groups.append({"colour": ends[blk[0]][2], "pts": pts, "pie": dict(bpie[anc])})
        for k, i in enumerate(blk):
            if ends[i][1] == RING_SEL:
                sel = (gi, k)
    anchored = {_centroid(gp["pts"]) for gp in groups}
    pickups = [(pos, pie) for pos, pie in blobs if pos not in anchored]
    # A pick-up can be half-hidden under a node in the current frame; its
    # colours are unambiguous in the level's entry frame, so read them there.
    entry_pies = _entry_blobs(_level_of(g))
    pickups = [(pos, entry_pies.get(pos, pie)) for pos, pie in pickups]
    for gp in groups:
        for q in gp["pts"]:
            covered |= set(_diamond(*q))
    base = _copy(g)
    for y in range(64):
        for x in range(1, 64):
            if (x, y) in covered:
                base[y][x] = FLOOR
    lv = _level_of(g)
    rings = _entry_rings(lv) or _find_rings(base)
    entry = _entry_for(lv)
    for y in range(64):
        for x in range(1, 64):
            if base[y][x] == LINE:
                base[y][x] = FLOOR
    if entry is not None:
        # A ring cell painted in a terrain colour is part of the map; restore
        # it even when the current frame has a segment lying on top of it.
        for pos, _ in rings:
            for dx, dy in _ring_offsets():
                v = entry[pos[1] + dy][pos[0] + dx]
                if v in _BLOCKED:
                    base[pos[1] + dy][pos[0] + dx] = v
    markset = set()
    for pos, ring in rings:
        for dx, dy in _ring_offsets():
            if (dx, dy) in ring:
                base[pos[1] + dy][pos[0] + dx] = FLOOR
            markset.add((pos[0] + dx, pos[1] + dy))
    for pos, _ in pickups:
        markset |= set(_blob_cells(*pos))
    filled = 0
    while filled < 64 and g[filled][0] == FLOOR:
        filled += 1
    acts = 0
    while acts + acts // 8 < filled:
        acts += 1
    # A ring is a live TARGET if some group's pie, plus some of the loose
    # pick-ups, can reproduce it; the rest are decoys.  Live-but-unclaimed
    # rings are drawn under the segments, everything else over them.
    live = set()
    for pos, ring in rings:
        for gp in groups:
            hit = False
            for r in range(0, len(pickups) + 1):
                for combo in itertools.combinations(range(len(pickups)), r):
                    pie = dict(gp["pie"])
                    for i in combo:
                        for k, v in pickups[i][1].items():
                            if v:
                                pie[k] = v
                    if _matches(pie, ring):
                        hit = True
                        break
                if hit or r >= 4:
                    break
            if hit:
                live.add(pos)
                break
    return {"groups": groups, "sel": sel, "base": base, "rings": rings,
            "pickups": pickups, "markset": markset, "live": live,
            "acts": acts, "level": lv}


def _matches(pie, ring):
    return all(_pie_colour(pie, dx, dy) == v for (dx, dy), v in ring.items())


def _solved(st):
    """Every group parked on a ring whose colours its pie reproduces."""
    out = []
    for gp in st["groups"]:
        anc = _centroid(gp["pts"])
        hit = None
        for pos, ring in st["rings"]:
            if pos == anc and _matches(gp["pie"], ring):
                hit = pos
        out.append(hit)
    return out


def _render(st):
    g = _copy(st["base"])
    # A ring belongs to the group whose pie already reproduces it; it is drawn
    # on top of that group's own lines, but under everybody else's.
    done = set(p for p in _solved(st) if p)

    def paint_ring(pos, ring):
        for (dx, dy), v in ring.items():
            g[pos[1] + dy][pos[0] + dx] = 0 if pos in done else v

    order = sorted(range(len(st["groups"])), key=lambda i: st["groups"][i]["colour"])
    for gi in order:
        gp = st["groups"][gi]
        anc = _centroid(gp["pts"])
        for q in gp["pts"]:
            for (px, py) in _seg(anc, q):
                if 0 < px < 64 and 0 <= py < 64:
                    g[py][px] = LINE
    for pos, ring in st["rings"]:
        paint_ring(pos, ring)
    for pos, pie in st["pickups"]:
        for (dx, dy), v in pie.items():
            g[pos[1] + dy][pos[0] + dx] = v
    for gi in order:
        gp = st["groups"][gi]
        for i, q in enumerate(gp["pts"]):
            ring = RING_SEL if st["sel"] == (gi, i) else RING_UNSEL
            for (px, py) in _diamond(*q):
                if 0 < px < 64 and 0 <= py < 64:
                    g[py][px] = ring
            g[q[1]][q[0]] = gp["colour"]
    # Anchors are painted last: an anchor blob covers another group's node.
    for gi in order:
        gp = st["groups"][gi]
        anc = _centroid(gp["pts"])
        for (px, py) in _blob_cells(*anc):
            if 0 < px < 64 and 0 <= py < 64:
                g[py][px] = _pie_colour(gp["pie"], px - anc[0], py - anc[1])
    a = st["acts"]
    filled = a + a // 8
    for y in range(64):
        g[y][0] = FLOOR if y < filled else 0
    return g


def predict(state, grid, action, x=None, y=None, level=None, entry_grid=None):
    st = dict(state)
    st["groups"] = [dict(gp, pts=list(gp["pts"]), pie=dict(gp["pie"]))
                    for gp in state["groups"]]
    st["pickups"] = list(state["pickups"])
    if action == 6 and x is not None:
        hit = None
        for gi, gp in enumerate(st["groups"]):
            for i, q in enumerate(gp["pts"]):
                if abs(q[0] - x) <= 2 and abs(q[1] - y) <= 2:
                    hit = (gi, i)
        if hit is not None:
            st["sel"] = hit
        elif st["sel"] is not None and _fits(st["base"], x, y):
            gi, i = st["sel"]
            gp = st["groups"][gi]
            old = gp["pts"][i]
            gp["pts"][i] = (x, y)
            if not _layout_ok(st, st["groups"]):
                gp["pts"][i] = old
    # An anchor standing on a loose pick-up absorbs its colours and clears it.
    for gp in st["groups"]:
        anc = _centroid(gp["pts"])
        for pos, pie in list(st["pickups"]):
            if pos == anc:
                merged = dict(gp["pie"])
                for k, v in pie.items():
                    if v:
                        merged[k] = v
                gp["pie"] = merged
                st["pickups"] = [q for q in st["pickups"] if q[0] != pos]
    st["acts"] = state["acts"] + 1
    g = _render(st)
    done = all(_solved(st))
    if done:
        lv = state.get("level") if level is None else level
        nxt = _entry_for((lv or 0) + 1)
        if nxt is not None:
            g = nxt
    return g, {"level_up": bool(done)}, st
