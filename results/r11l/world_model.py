def _level_of(g):
    """Which recorded level is this frame from?  Terrain never moves, and no
    sprite ever paints a blocked colour, so the blocked-cell set identifies it."""
    global _SIGS
    if _SIGS is None:
        _SIGS = {lv: _terrain_sig(_entry_for(lv)) for lv in _LEVEL_ENTRIES}
    sig = _terrain_sig(g)
    # Sprites can both hide terrain and paint in a terrain colour, so match on
    # the closest blocked-cell set rather than an exact one.
    best, bestd = None, 1e9
    for lv, s in _SIGS.items():
        d = len(s ^ sig)
        if d < bestd:
            best, bestd = lv, d
    return best if bestd <= 60 else None


def _entry_for(level):
    rows = _LEVEL_ENTRIES.get(level)
    if rows is None:
        return None
    return [[int(ch, 16) for ch in row] for row in rows]


RING_SEL = 0
RING_UNSEL = 3
CENTRE_ANCHOR = 6
LINE = 1
FLOOR = 5


def _copy(g):
    return [row[:] for row in g]


def _diamond(cx, cy, r=2):
    for dy in range(-r, r + 1):
        for dx in range(-r, r + 1):
            if abs(dx) + abs(dy) <= r:
                yield cx + dx, cy + dy


def _blob(cx, cy):
    for dy in range(-2, 3):
        for dx in range(-2, 3):
            if abs(dx) == 2 and abs(dy) == 2:
                continue
            yield cx + dx, cy + dy


def _blob_cells(cx, cy):
    return [(cx + dx, cy + dy) for dy in range(-2, 3) for dx in range(-2, 3)
            if not (abs(dx) == 2 and abs(dy) == 2)]


def _find_blobs(g):
    """Every 5x5-minus-corners sprite: group anchors AND the loose colour
    pick-ups that level 4 scatters around.  Both are painted from a 21-cell
    'pie' (an angular colour partition, 0 = still empty)."""
    out = []
    for y in range(2, 62):
        for x in range(2, 62):
            if any(g[y + dy][x + dx] not in (FLOOR, LINE)
                   for dx in (-2, 2) for dy in (-2, 2)):
                continue          # the 4 skipped corners must be clear terrain
            vals = [g[py][px] for px, py in _blob_cells(x, y)]
            if all(v not in (FLOOR, LINE) for v in vals):
                out.append(((x, y), {(px - x, py - y): g[py][px]
                                     for px, py in _blob_cells(x, y)}))
    return out


def _scan(g, covered):
    """Endpoint nodes (pos, ring, colour); blob sprites may occlude them."""
    ends = []
    for y in range(2, 62):
        for x in range(2, 62):
            c = g[y][x]
            if c in (FLOOR, LINE, 0, 3) + _BLOCKED or (x, y) in covered:
                continue
            vals = [g[py][px] for px, py in _diamond(x, y)
                    if (px, py) != (x, y) and (px, py) not in covered]
            if len(vals) >= 4 and len(set(vals)) == 1 and vals[0] in (RING_SEL, RING_UNSEL):
                ends.append(((x, y), vals[0], c))
    return ends


def _partitions(items):
    if not items:
        yield []
        return
    first, rest = items[0], items[1:]
    for parts in _partitions(rest):
        for i in range(len(parts)):
            yield parts[:i] + [[first] + parts[i]] + parts[i + 1:]
        yield [[first]] + parts


def _split_groups(ends, blobpos):
    """Endpoints sharing a colour may still be SEPARATE groups (level 4).
    A block is real only if its centroid carries an anchor blob."""
    best = None
    for parts in _partitions(list(range(len(ends)))):
        ok = True
        used = []
        for blk in parts:
            cols = {ends[i][2] for i in blk}
            if len(cols) != 1:
                ok = False
                break
            anc = _centroid([ends[i][0] for i in blk])
            if anc not in blobpos or anc in used:
                ok = False
                break
            used.append(anc)
        if ok and (best is None or len(parts) < len(best)):
            best = parts
    return best


def _rnd(v0, delta):
    """Offset from the origin, rounding the DELTA half away from zero."""
    if delta < 0:
        return v0 - int(-delta + 0.5)
    return v0 + int(delta + 0.5)


def _seg(a, b):
    (x0, y0), (x1, y1) = a, b
    dx, dy = x1 - x0, y1 - y0
    if dx == 0 and dy == 0:
        return [a]
    cells = []
    if abs(dy) >= abs(dx):
        step = 1 if dy > 0 else -1
        for y in range(y0, y1 + step, step):
            cells.append((_rnd(x0, dx * (y - y0) / dy), y))
    else:
        step = 1 if dx > 0 else -1
        for x in range(x0, x1 + step, step):
            cells.append((x, _rnd(y0, dy * (x - x0) / dx)))
    return cells


def _centroid(pts):
    return (sum(p[0] for p in pts) // len(pts), sum(p[1] for p in pts) // len(pts))


def _fits(base, cx, cy):
    for px, py in _diamond(cx, cy):
        if not (0 < px < 64 and 0 <= py < 64) or base[py][px] != FLOOR:
            return False
    return True


def _open(base, marks, px, py):
    """Floor, or a target-marker cell (markers are drawn over the lines)."""
    if not (0 < px < 64 and 0 <= py < 64):
        return False
    return base[py][px] == FLOOR or (px, py) in marks


